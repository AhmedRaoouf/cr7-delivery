<?php

namespace App\Console\Commands;

use App\Actions\Admin\GenerateSettlementAction;
use App\Models\Restaurant;
use App\Support\SettlementCycle;
use Illuminate\Console\Command;
use Throwable;

/**
 * doc 103 / doc 104 — «عمل تسوية كل 14 يوم»: a draft statement for every place on a
 * commission, the day after each of its periods ends.
 *
 * Each place has its own cycle ({@see SettlementCycle}): periods from the day its contract
 * starts (`restaurants.settlement_starts_on`), `settlement_every_days` long (or
 * `settlements.cycle_days`). A place at 0 % has none and gets no automatic statement. Once
 * a period is over, a place with a delivered order in it that no statement has claimed gets
 * one draft, written by `GenerateSettlementAction` exactly as an admin's would be. The
 * office reviews it and records the payment.
 *
 * Safe to run any number of times: an order is claimed by the first statement that takes
 * it, so a second run finds nothing left in the period and writes nothing. It runs hourly
 * so a missed hour (a deploy, a cron hiccup) is made up by the next one.
 *
 * Orders delivered before a place's start are not swept up — a statement for them is still
 * generated by hand on `ADM-33`.
 */
class SettlementCycleCommand extends Command
{
    protected $signature = 'cr7:settlement-cycle {--dry-run : Print what would be written and write nothing}';

    protected $description = 'Write the draft statements of the places on a commission whose period just ended (doc 103, doc 104)';

    public function handle(GenerateSettlementAction $action): int
    {
        $places = Restaurant::withTrashed()
            ->where('commission_rate', '>', 0)
            ->whereNotNull('settlement_starts_on')
            ->orderBy('id')
            ->get();

        $written = 0;
        $onCycle = 0;

        foreach ($places as $place) {
            $cycle = SettlementCycle::of($place);
            if ($cycle === null) {
                continue;
            }
            $onCycle++;

            foreach ($cycle->completedPeriods() as [$start, $end]) {
                if (! GenerateSettlementAction::unsettled((int) $place->id, $start, $end)->exists()) {
                    continue;
                }

                if ($this->option('dry-run')) {
                    $this->line("  would settle place {$place->id} for {$start} → {$end}");
                    $written++;

                    continue;
                }

                try {
                    $settlement = $action->execute(null, 'restaurant', (int) $place->id, $start, $end);
                    $this->line("  place {$place->id} {$start} → {$end}: statement {$settlement->id}, net {$settlement->net_amount}");
                    $written++;
                } catch (Throwable $e) {
                    // One place's failure must not stop the others' statements.
                    report($e);
                    $this->error("  place {$place->id}: {$e->getMessage()}");
                }
            }
        }

        $this->info("{$onCycle} place(s) on a cycle, {$written} statement(s).");

        return self::SUCCESS;
    }
}
