<?php

namespace App\Console\Commands;

use App\Actions\Admin\GenerateSettlementAction;
use App\Models\Restaurant;
use App\Support\BusinessTime;
use App\Support\SettingsCatalog;
use Illuminate\Console\Command;
use Illuminate\Support\Carbon;
use Throwable;

/**
 * doc 103 — «عمل تسوية كل 14 يوم»: a draft statement for every place, the day after each
 * period ends.
 *
 * Periods run back to back from `settlements.cycle_start`, `settlements.cycle_days` long
 * (Cairo days). Once a period is over, every place with a delivered order in it that no
 * statement has claimed gets one draft, written by `GenerateSettlementAction` exactly as an
 * admin's would be. The office reviews it and records the payment.
 *
 * Safe to run any number of times: an order is claimed by the first statement that takes
 * it, so a second run finds nothing left in the period and writes nothing. It runs hourly
 * so a missed hour (a deploy, a cron hiccup) is made up by the next one.
 *
 * Orders delivered before `cycle_start` are not swept up — a statement for them is still
 * generated by hand on `ADM-33`.
 */
class SettlementCycleCommand extends Command
{
    protected $signature = 'cr7:settlement-cycle {--dry-run : Print what would be written and write nothing}';

    protected $description = 'Write the draft place statements for the 14-day period that just ended (doc 103)';

    public function handle(GenerateSettlementAction $action): int
    {
        $periods = self::completedPeriods();

        if ($periods === []) {
            $this->line('No period has ended yet, or the cycle is off.');

            return self::SUCCESS;
        }

        $written = 0;

        foreach ($periods as [$start, $end]) {
            $this->line("Period {$start} → {$end}");

            foreach (Restaurant::withTrashed()->orderBy('id')->pluck('id') as $restaurantId) {
                if (! GenerateSettlementAction::unsettled((int) $restaurantId, $start, $end)->exists()) {
                    continue;
                }

                if ($this->option('dry-run')) {
                    $this->line("  would settle place {$restaurantId}");
                    $written++;

                    continue;
                }

                try {
                    $settlement = $action->execute(null, 'restaurant', (int) $restaurantId, $start, $end);
                    $this->line("  place {$restaurantId}: statement {$settlement->id}, net {$settlement->net_amount}");
                    $written++;
                } catch (Throwable $e) {
                    // One place's failure must not stop the others' statements.
                    report($e);
                    $this->error("  place {$restaurantId}: {$e->getMessage()}");
                }
            }
        }

        $this->info("{$written} statement(s).");

        return self::SUCCESS;
    }

    /**
     * The last few periods that are over, oldest first — three, so a cron that was down
     * for a whole period still writes it, without the hourly run growing with the years.
     *
     * @return list<array{0: string, 1: string}>
     */
    public static function completedPeriods(?Carbon $today = null, int $lookBack = 3): array
    {
        $last = self::lastCompletedPeriod($today);

        if ($last === null) {
            return [];
        }

        $days = SettingsCatalog::int('settlements.cycle_days');
        $anchor = Carbon::createFromFormat('Y-m-d', (string) SettingsCatalog::get('settlements.cycle_start'), BusinessTime::timezone())->startOfDay();
        $periods = [];
        $start = Carbon::createFromFormat('Y-m-d', $last[0], BusinessTime::timezone())->startOfDay();

        for ($i = 0; $i < $lookBack && $start->greaterThanOrEqualTo($anchor); $i++) {
            array_unshift($periods, [$start->toDateString(), $start->copy()->addDays($days - 1)->toDateString()]);
            $start = $start->copy()->subDays($days);
        }

        return $periods;
    }

    /**
     * The most recent period whose last day is before today (Cairo), as two
     * `Y-m-d` strings — or null when the cycle is off or the first period is not over.
     *
     * @return array{0: string, 1: string}|null
     */
    public static function lastCompletedPeriod(?Carbon $today = null): ?array
    {
        $days = SettingsCatalog::int('settlements.cycle_days');

        if ($days <= 0) {
            return null;
        }

        try {
            $anchor = Carbon::createFromFormat('Y-m-d', (string) SettingsCatalog::get('settlements.cycle_start'), BusinessTime::timezone())->startOfDay();
        } catch (Throwable) {
            return null;
        }

        $today = ($today ?? BusinessTime::now())->copy()->setTimezone(BusinessTime::timezone())->startOfDay();
        $elapsed = (int) $anchor->diffInDays($today, false);
        $completed = intdiv(max(0, $elapsed), $days);

        if ($elapsed < $days || $completed < 1) {
            return null;
        }

        $start = $anchor->copy()->addDays(($completed - 1) * $days);
        $end = $start->copy()->addDays($days - 1);

        return [$start->toDateString(), $end->toDateString()];
    }
}
